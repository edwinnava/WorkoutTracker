export function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

export const BUILT_IN_EXERCISES: Exercise[] = ROWS.map(([name, muscle, equipment, type = W, secondary]) => ({
  id: slugify(name),
  name,
  muscle,
  equipment,
  type,
  ...(secondary ? { secondary } : {}),
}));

